#!/usr/bin/env python3
"""Generates the signatures the type checker knows for the built-in methods
and the standard library, from the tables in ideas/stdlib. The docs are the
source of truth, so the checker and the docs never disagree.

    python3 tools/docs/prelude.py

It writes crates/lakescript/src/checker/prelude.txt. Run it after changing a
signature in the docs.
"""
import re
from pathlib import Path

repo = Path(__file__).resolve().parent.parent.parent
stdlib = repo / 'ideas' / 'stdlib'
out = repo / 'crates' / 'lakescript' / 'src' / 'checker' / 'prelude.txt'

# The type each file describes, with the names of its type parameters
TYPES = {
    'any': 'any', 'string': 'string', 'number': 'number', 'bool': 'bool', 'symbol': 'symbol',
    'regex': 'regex', 'range': 'range', 'command': 'command', 'list': 'list<T>', 'map': 'map<K, V>',
}
# The modules written in Rust, by their file. The ones written in Lakescript
# (i.e. std/http) get their types from their own code
MODULES = {'general': 'general', 'fs': 'std/fs', 'path': 'std/path', 'env': 'std/env', 'io': 'std/io',
           'process': 'std/process', 'format/json': 'std/format/json', 'format/csv': 'std/format/csv',
           'time': 'std/time'}

# Types described outside ideas/stdlib, and the Rust parts of the modules
# written in Lakescript, which aren't documented since scripts never use them
EXTRA = '''
module std/http/native
map<string, any> send(string $method, string $url, any $body, map<string, string> $headers, ?number $timeout, ?string $path);

type result<T, E>
bool isOk();
bool isError();
T orElse(T $default);
T orElseGet(() -> T $fn);
result<U, E> map((T) -> U $fn);
?T orNull();
T throw();
?E error();

type exception
string message();
string typeName();
number line();
'''


def cells(line):
    line = line.strip().replace('\\|', '\x01')
    return [c.strip().replace('\x01', '|') for c in line.strip('|').split('|')]


def members(path):
    """The signatures in the Method/Function/Constant tables of a file."""
    lines = path.read_text().splitlines()
    result = []
    i = 0
    while i < len(lines):
        row = lines[i].strip()
        if row.startswith('|') and cells(row)[0] in ('Method', 'Function', 'Constant'):
            constant = cells(row)[0] == 'Constant'
            i += 2
            while i < len(lines) and lines[i].strip().startswith('|'):
                c = cells(lines[i])
                member, returns = c[0].strip('`'), c[1].strip('`')
                # `.as()` and `.is()` take a type, and the checker handles them itself
                if member.startswith(('as(', 'is(')):
                    i += 1
                    continue
                if constant:
                    result.append(f'const {returns} {member};')
                else:
                    result.append(f'{returns} {member};')
                i += 1
            continue
        i += 1
    return result


def main():
    parts = ['# Generated by tools/docs/prelude.py from ideas/stdlib. Don\'t edit it by hand.']
    for name, header in TYPES.items():
        parts.append(f'\ntype {header}')
        parts.extend(members(stdlib / 'types' / f'{name}.md'))
    for name, header in MODULES.items():
        parts.append(f'\nmodule {header}')
        parts.extend(members(stdlib / f'{name}.md'))
    parts.append(EXTRA.rstrip())
    text = '\n'.join(parts) + '\n'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    count = sum(1 for l in text.splitlines() if l.endswith(';'))
    print(f'{out}: {count} signatures')


main()
